import { useEffect, useRef, useState, type FormEvent } from "react";
import { Bot, Check, LoaderCircle, Send, Settings2, Square, Trash2 } from "lucide-react";
import type { AppProps } from "../../types";
import {
  DEFAULT_OLLAMA_CONFIG,
  normalizeOllamaEndpoint,
  normalizeOllamaModel,
  readOllamaConfig,
  requestOllamaReply,
  writeOllamaConfig,
  type OllamaConfig,
  type OllamaMessage,
} from "../../lib/ollama";
import "./Assistant.css";

export function Assistant(_props: AppProps) {
  const [config, setConfig] = useState<OllamaConfig>(() => readOllamaConfig());
  const [endpointDraft, setEndpointDraft] = useState(config.endpoint);
  const [modelDraft, setModelDraft] = useState(config.model);
  const [messages, setMessages] = useState<OllamaMessage[]>([]);
  const [input, setInput] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [saved, setSaved] = useState(false);
  const controller = useRef<AbortController | null>(null);

  useEffect(() => () => controller.current?.abort(), []);

  function saveConfig(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    setError("");
    setSaved(false);
    if (!normalizeOllamaEndpoint(endpointDraft) || !normalizeOllamaModel(modelDraft)) {
      setError("Use a local loopback URL (for example http://localhost:11434) and a valid Ollama model name.");
      return;
    }
    try {
      const next = writeOllamaConfig({ endpoint: endpointDraft, model: modelDraft });
      setConfig(next);
      setEndpointDraft(next.endpoint);
      setModelDraft(next.model);
      setSaved(true);
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "Could not save the local assistant settings.");
    }
  }

  async function sendMessage(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const text = input.trim();
    if (!text || loading || text.length > 4000) return;
    const userMessage: OllamaMessage = { role: "user", content: text };
    const nextMessages = [...messages, userMessage];
    setMessages(nextMessages);
    setInput("");
    setError("");
    setLoading(true);
    const requestController = new AbortController();
    controller.current = requestController;
    const timeout = window.setTimeout(() => requestController.abort(), 90_000);
    try {
      const content = await requestOllamaReply(config, nextMessages.slice(-12), requestController.signal);
      setMessages((current) => [...current, { role: "assistant", content }]);
    } catch (cause) {
      setError(cause instanceof DOMException && cause.name === "AbortError"
        ? "The request was canceled or timed out."
        : cause instanceof Error ? cause.message : "The local assistant request failed.");
    } finally {
      window.clearTimeout(timeout);
      if (controller.current === requestController) controller.current = null;
      setLoading(false);
    }
  }

  function cancelRequest() {
    controller.current?.abort();
  }

  return (
    <main className="ollama-assistant">
      <header className="ollama-assistant__header">
        <span className="ollama-assistant__mark"><Bot size={20} /></span>
        <div><h1>Local Assistant</h1><p>Responses come from your Ollama server.</p></div>
      </header>

      <form className="ollama-assistant__config" onSubmit={saveConfig}>
        <div className="ollama-assistant__config-title"><Settings2 size={15} /><strong>Connection</strong><span>Saved on this device</span></div>
        <div className="ollama-assistant__config-fields">
          <label>Local Ollama URL
            <input value={endpointDraft} onChange={(event) => setEndpointDraft(event.target.value)} autoComplete="url" spellCheck={false} />
          </label>
          <label>Model
            <input value={modelDraft} onChange={(event) => setModelDraft(event.target.value)} placeholder={DEFAULT_OLLAMA_CONFIG.model} spellCheck={false} />
          </label>
          <button className="ollama-assistant__save" type="submit">{saved ? <Check size={14} /> : null}{saved ? "Saved" : "Save"}</button>
        </div>
        <p className="ollama-assistant__privacy">Chat text is sent to this loopback server only. OrbitOS does not provide a model or proxy. Install/run Ollama locally, pull the chosen model, and allow this site origin in Ollama's CORS settings.</p>
      </form>

      <section className="ollama-assistant__chat" aria-label="Conversation">
        {messages.length === 0 ? (
          <div className="ollama-assistant__empty">
            <Bot size={30} />
            <strong>Connect to your local model</strong>
            <span>Save a model name, then send a message. No sample responses are generated by OrbitOS.</span>
          </div>
        ) : (
          <div className="ollama-assistant__messages" aria-live="polite">
            {messages.map((message, index) => (
              <article key={`${index}-${message.role}`} className={`ollama-assistant__message ollama-assistant__message--${message.role}`}>
                <strong>{message.role === "user" ? "You" : config.model}</strong>
                <p>{message.content}</p>
              </article>
            ))}
            {loading && <div className="ollama-assistant__working"><LoaderCircle size={15} /> Waiting for the local model…</div>}
          </div>
        )}
        {error && <p className="ollama-assistant__error" role="alert">{error}</p>}
        <div className="ollama-assistant__actions">
          {messages.length > 0 && <button type="button" className="ollama-assistant__clear" onClick={() => { setMessages([]); setError(""); }} aria-label="Clear conversation"><Trash2 size={14} /> Clear</button>}
        </div>
      </section>

      <form className="ollama-assistant__composer" onSubmit={(event) => void sendMessage(event)}>
        <textarea
          value={input}
          onChange={(event) => setInput(event.target.value)}
          onKeyDown={(event) => {
            if (event.key === "Enter" && !event.shiftKey) {
              event.preventDefault();
              event.currentTarget.form?.requestSubmit();
            }
          }}
          placeholder="Message your local model…"
          aria-label="Message your local model"
          maxLength={4000}
          rows={2}
          disabled={loading}
        />
        {loading
          ? <button className="ollama-assistant__send" type="button" onClick={cancelRequest} aria-label="Cancel request"><Square size={15} /></button>
          : <button className="ollama-assistant__send" type="submit" disabled={!input.trim()} aria-label="Send message"><Send size={15} /></button>}
      </form>
    </main>
  );
}
